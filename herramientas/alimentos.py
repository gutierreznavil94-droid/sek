    out = []
    for i, (n, cat, k, p, ch, g, por, gr, fu, up) in enumerate(F):
        if n in vistos: raise SystemExit('repetido: ' + n)
        vistos.add(n)
        out.append({'id': f't{i+1:03d}', 'n': n, 'cat': cat, 'kcal': k, 'p': p, 'c': ch, 'g': g, 'por': por, 'gr': gr, 'f': fu, **({'up': 1} if up else {})})
